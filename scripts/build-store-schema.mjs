#!/usr/bin/env node
// Regenerates the store page's Product JSON-LD and the visible product cards from
// src/data/store-products.js, so a new product can never ship with markup that Search Console
// rejects (the 2026-08 Product snippets errors were offers with a priceCurrency and no price).
//
//   node scripts/build-store-schema.mjs                  # write
//   node scripts/build-store-schema.mjs --check          # exit 1 if store.html is stale
//   node scripts/build-store-schema.mjs --from-gumroad   # refresh price/image/name from Gumroad first
//
// Kept as a generator rather than server-side rendering because store.html is served as a
// static file from Vercel's CDN, and Google should not have to run JavaScript to see an offer.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  GUMROAD_STORE,
  PRICE_VALID_UNTIL,
  RETURN_POLICY,
  STORE_ORIGIN,
  STORE_PATH,
  STORE_PRODUCTS,
  formatPrice,
  productUrl,
} from "../src/data/store-products.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const storePage = path.join(root, "public", "store.html");
const dataFile = path.join(root, "src", "data", "store-products.js");

const SCHEMA_BEGIN = "<!-- store schema: generated by scripts/build-store-schema.mjs -->";
const SCHEMA_END = "<!-- /store schema -->";
const CARDS_BEGIN = "<!-- store cards: generated by scripts/build-store-schema.mjs -->";
const CARDS_END = "<!-- /store cards -->";

const pageUrl = `${STORE_ORIGIN}${STORE_PATH}`;

function escapeHtml(value) {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * test/phase2-public-pages.test.js bans literal em/en dashes in the public pages, so product
 * names that contain one are emitted as JSON \u escapes. Same bytes to a parser, no dash in
 * the file.
 */
function escapeDashes(json) {
  return json.replace(/[–—]/g, (char) => `\\u${char.codePointAt(0).toString(16)}`);
}

function offerFor(product) {
  return {
    "@type": "Offer",
    url: productUrl(product),
    price: product.price,
    priceCurrency: product.priceCurrency,
    priceValidUntil: PRICE_VALID_UNTIL,
    availability: "https://schema.org/InStock",
    itemCondition: "https://schema.org/NewCondition",
    seller: { "@type": "Organization", name: "Sleek Academia" },
    hasMerchantReturnPolicy: { "@id": `${pageUrl}#return-policy` },
  };
}

/**
 * aggregateRating and review are emitted only when a product carries real collected ratings.
 * Absent ratings are a Search Console warning; invented ratings are a policy violation.
 */
function ratingFor(product) {
  const rating = product.rating;
  if (!rating) return {};
  if (!(rating.reviewCount > 0) || !(Number(rating.ratingValue) > 0)) {
    throw new Error(`${product.sku}: rating present but ratingValue/reviewCount are not positive`);
  }
  const node = {
    aggregateRating: {
      "@type": "AggregateRating",
      ratingValue: String(rating.ratingValue),
      reviewCount: rating.reviewCount,
      bestRating: String(rating.bestRating ?? 5),
    },
  };
  if (Array.isArray(rating.reviews) && rating.reviews.length > 0) {
    node.review = rating.reviews.map((review) => ({
      "@type": "Review",
      author: { "@type": "Person", name: review.author },
      datePublished: review.datePublished,
      reviewRating: {
        "@type": "Rating",
        ratingValue: String(review.ratingValue),
        bestRating: String(review.bestRating ?? 5),
      },
      reviewBody: review.body,
    }));
  }
  return node;
}

function productNode(product) {
  return {
    "@type": "Product",
    name: product.schemaName,
    description: product.description,
    url: productUrl(product),
    image: product.image,
    sku: product.sku,
    brand: { "@type": "Brand", name: "Sleek Academia" },
    ...ratingFor(product),
    offers: offerFor(product),
  };
}

export function buildGraph(products = STORE_PRODUCTS) {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "CollectionPage",
        "@id": `${pageUrl}#page`,
        name: "Sleek Academia Study Materials",
        url: pageUrl,
        description: "Digital study materials for demanding coursework and professional exams.",
        provider: {
          "@type": "Organization",
          name: "Sleek Academia",
          logo: `${STORE_ORIGIN}/images/brand/sleek-academia-logo.webp`,
          sameAs: [
            "https://instagram.com/sleek_academia",
            "https://tiktok.com/@sleek_e_learn",
            "https://www.linkedin.com/in/sir-maxwell-763b9818b",
            "https://www.youtube.com/channel/UCID9SDULAMHqyKjB65Bo01A",
          ],
        },
      },
      {
        "@type": "ItemList",
        "@id": `${pageUrl}#products`,
        name: "Sleek Academia Study Materials",
        itemListOrder: "https://schema.org/ItemListUnordered",
        numberOfItems: products.length,
        itemListElement: products.map((product, index) => ({
          "@type": "ListItem",
          position: index + 1,
          item: productNode(product),
        })),
      },
      {
        "@type": "MerchantReturnPolicy",
        "@id": `${pageUrl}#return-policy`,
        applicableCountry: RETURN_POLICY.countries,
        returnPolicyCategory: "https://schema.org/MerchantReturnFiniteReturnWindow",
        merchantReturnDays: RETURN_POLICY.days,
        returnMethod: "https://schema.org/ReturnByMail",
        returnFees: RETURN_POLICY.freeReturns
          ? "https://schema.org/FreeReturn"
          : "https://schema.org/ReturnFeesCustomerResponsibility",
      },
    ],
  };
}

function schemaBlock(products) {
  const json = escapeDashes(JSON.stringify(buildGraph(products), null, 2))
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
  return [
    `  ${SCHEMA_BEGIN}`,
    `  <script type="application/ld+json">`,
    json,
    `  </script>`,
    `  ${SCHEMA_END}`,
  ].join("\n");
}

function cardsBlock(products) {
  const cards = products.map((product) => {
    const href = `${productUrl(product)}?wanted=true`;
    return [
      `          <article class="platform-card product-card-v2" data-reveal>`,
      `<div class="product-icon">${escapeHtml(product.icon)}</div>`,
      `<h3>${escapeHtml(product.cardTitle)}</h3>`,
      `<p>${escapeHtml(product.description)}</p>`,
      `<p class="product-price">${formatPrice(product)} &middot; one-time digital purchase</p>`,
      `<a class="platform-button primary" href="${href}">View on Gumroad</a>`,
      `</article>`,
    ].join("");
  });
  return [`          ${CARDS_BEGIN}`, ...cards, `          ${CARDS_END}`].join("\n");
}

/** The visible refund/price sentence has to match the offer and the return policy. */
export function summarySentence(products = STORE_PRODUCTS) {
  const prices = [...new Set(products.map((product) => formatPrice(product)))];
  const priceText =
    prices.length === 1 ? `a one-time digital purchase of ${prices[0]}` : "a one-time digital purchase";
  const refund = RETURN_POLICY.freeReturns ? ", at no cost to you" : "";
  return `Every item is ${priceText}, delivered instantly through Gumroad. Refunds are available within ${RETURN_POLICY.days} days of purchase${refund}.`;
}

function replaceBlock(html, begin, end, replacement, label) {
  const pattern = new RegExp(`[ \\t]*${begin}[\\s\\S]*?${end}`);
  if (!pattern.test(html)) throw new Error(`store.html: ${label} markers not found`);
  return html.replace(pattern, replacement);
}

export function render(html, products = STORE_PRODUCTS) {
  let next = replaceBlock(html, SCHEMA_BEGIN, SCHEMA_END, schemaBlock(products), "schema");
  next = replaceBlock(next, CARDS_BEGIN, CARDS_END, cardsBlock(products), "cards");
  return next.replace(
    /(<p class="platform-copy" data-reveal id="store-terms"[^>]*>)[\s\S]*?(<\/p>)/,
    (_match, open, close) => `${open}${summarySentence(products)}${close}`,
  );
}

async function refreshFromGumroad() {
  const token = process.env.GUMROAD_ACCESS_TOKEN;
  if (!token) throw new Error("GUMROAD_ACCESS_TOKEN is not set");
  const response = await fetch("https://api.gumroad.com/v2/products", {
    headers: { Authorization: `Bearer ${token}` },
    signal: AbortSignal.timeout(15_000),
  });
  const payload = await response.json();
  if (!payload.success) throw new Error("Gumroad API rejected the request");

  const bySku = new Map(payload.products.map((product) => [product.id, product]));
  const source = fs.readFileSync(dataFile, "utf8");
  let updated = source;
  let changes = 0;

  for (const product of STORE_PRODUCTS) {
    const live = bySku.get(product.sku) ?? payload.products.find((p) => p.permalink === product.gumroadPermalink);
    if (!live) {
      console.warn(`! ${product.sku} is no longer published on Gumroad — remove it or unlist the card`);
      continue;
    }
    const price = (live.price / 100).toFixed(2);
    if (price !== product.price) {
      updated = updated.replace(`price: "${product.price}",\n    priceCurrency: "${product.priceCurrency}",\n    image: "${product.image}"`, `price: "${price}",\n    priceCurrency: "${live.currency?.toUpperCase() ?? product.priceCurrency}",\n    image: "${live.cover_url ?? product.image}"`);
      changes += 1;
      console.log(`  ${product.sku}: price ${product.price} -> ${price}`);
    }
  }
  if (changes > 0) fs.writeFileSync(dataFile, updated);
  console.log(changes > 0 ? `Updated ${changes} product(s) in src/data/store-products.js` : "Gumroad data already matches");
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes("--from-gumroad")) await refreshFromGumroad();

  const current = fs.readFileSync(storePage, "utf8");
  const next = render(current);

  if (args.includes("--check")) {
    if (current !== next) {
      console.error("store.html is out of date — run: npm run build:store");
      process.exit(1);
    }
    console.log(`store.html is up to date (${STORE_PRODUCTS.length} products, ${GUMROAD_STORE})`);
    return;
  }

  if (current === next) {
    console.log("store.html already matches src/data/store-products.js");
    return;
  }
  fs.writeFileSync(storePage, next);
  console.log(`Wrote store.html from ${STORE_PRODUCTS.length} product(s)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  await main();
}
